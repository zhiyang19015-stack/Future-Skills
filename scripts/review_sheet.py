"""The human review sheet for the Career Stress Test: 20 occupations, one table to mark by hand.

The plan's acceptance test asks for at least 20 occupations across clerical, professional,
service, manufacturing, health and trade work to be reviewed by people. This script writes what
the stress test says for each of data/review_occupations.csv under slow, moderate and fast
adoption (default resistance), with both AI sources and the closest routes, and leaves a column
for the reviewer's verdict. It does not review anything itself: the verdict columns stay empty
until a career counsellor or subject expert fills them in.

Usage:
    python scripts/review_sheet.py            # -> docs/stress_test_review.md
"""

import csv
import io
import sys
from pathlib import Path

import matching
import outlook
import stress_test

ROOT = Path(__file__).resolve().parents[1]


def review_rows() -> list[dict]:
    return list(csv.DictReader(io.StringIO((ROOT / "data" / "review_occupations.csv").read_text(encoding="utf-8-sig"))))


def sheet(data: dict | None = None) -> str:
    data = data or matching.load_data()
    lines = ["# Career Stress Test: review sheet", "",
             "Generated by `scripts/review_sheet.py` from `data/review_occupations.csv`. Each row is what the stress test "
             "shows under slow, moderate and fast adoption with the default 30% resistance. **The reviewer columns are "
             "empty on purpose**: fill them in with a career counsellor or someone who does the job, then record the "
             "agreement rate and the reasons for each \"no\".", "",
             "Task mix = share of the job's work (by task importance) that is likely automated / augmented / human-led / "
             "not enough evidence. Observed = Anthropic Economic Index AI share. ILO = WP140 mean exposure (0-1) and gradient.",
             "", "| Group | Occupation | Observed | ILO | Mix slow | Mix moderate | Mix fast | Outlook (s/m/f) | Sources | "
             "Top routes | Plausible? (yes/no) | Reviewer note |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in review_rows():
        r = stress_test.run(row["occ_id"], data, {"adoption": outlook.SCENARIOS["moderate"]["adoption"]})
        mix = lambda m: " / ".join(f"{m[c]:.0f}" for c in stress_test.CATEGORIES)  # noqa: E731
        x = r["ilo"]
        ilo = f"{x['mean']:.2f} {x['gradient']}" if x else "none"
        sources = "disagree" if x and x["disagree"] else "agree" if x else "ILO missing"
        outlooks = "/".join(f"{v['outlook']:.0f}" for v in r["scenarios"].values())
        routes = "; ".join(f"{t['title']} ({t['coverage']:.0f}%)" for t in r["routes"][:3])
        s = r["scenarios"]
        lines.append(f"| {row['group']} | {r['occupation']['title']} | {r['outlook']['ai_share']:.0f}% | {ilo} | "
                     f"{mix(s['slow']['mix'])} | {mix(s['moderate']['mix'])} | {mix(s['fast']['mix'])} | {outlooks} | "
                     f"{sources} | {routes} |  |  |")
    lines += ["", "Why each occupation is in the set:", ""]
    lines += [f"- **{data['by_id'][r['occ_id']]['title']}** ({r['group']}): {r['why_in_set']}" for r in review_rows()]
    return "\n".join(lines) + "\n"


def main() -> int:
    out = ROOT / "docs" / "stress_test_review.md"
    out.write_text(sheet(), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
