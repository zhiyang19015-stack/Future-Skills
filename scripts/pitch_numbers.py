"""Every number the pitch material quotes, read from the result files, so the deck, the demo script and the
Q&A sheet can be checked against them (tests/test_pitch_numbers.py). Nothing is typed by hand.

    docs/eval_results.json     scripts/eval.py, held-out set a (E01-E40)
    docs/judge_check.json      scripts/judge_check.py (the 5 demo people, the data)
    docs/impact_verification.md is not read: its KPI numbers come from scripts/impact_report.py directly

    python scripts/pitch_numbers.py --write    # docs/pitch/numbers.md and docs/pitch/numbers.json
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
sys.path.insert(0, str(ROOT / "scripts"))


def pct(s: dict) -> str:
    return f"{s['pct']:g}%"


def numbers() -> dict:
    ev = json.loads((DOCS / "eval_results.json").read_text(encoding="utf-8"))
    jc = json.loads((DOCS / "judge_check.json").read_text(encoding="utf-8"))
    now, v1 = ev["versions"]["now"]["summary"]["all"], ev["versions"]["v1"]["summary"]["all"]
    common = now["common_first"][:5]
    second = jc["radar"]["second_source"]
    import impact_report
    imp = impact_report.report()
    return {
        "eval_first_ok": pct(now["first_ok"]), "eval_first_ok_k": f"{now['first_ok']['k']}/{now['first_ok']['n']}",
        "eval_first_ok_ci": f"{now['first_ok']['ci'][0]:g}–{now['first_ok']['ci'][1]:g}",
        "eval_top5_ok": pct(now["top5_ok"]), "eval_top5_ok_k": f"{now['top5_ok']['k']}/{now['top5_ok']['n']}",
        "eval_top5_ok_ci": f"{now['top5_ok']['ci'][0]:g}–{now['top5_ok']['ci'][1]:g}",
        "eval_top5_bad": pct(now["top5_bad"]),
        "v1_first_ok": pct(v1["first_ok"]), "v1_top5_ok": pct(v1["top5_ok"]),
        "eval_first_changed": pct(now["first_changed"]),
        "eval_first_changed_k": f"{now['first_changed']['k']}/{now['first_changed']['n']}",
        "eval_top5_set_changed": pct(now["top5_set_changed"]),
        "eval_top5_set_changed_k": f"{now['top5_set_changed']['k']}/{now['top5_set_changed']['n']}",
        "v1_first_changed": pct(v1["first_changed"]),
        "eval_free": pct(now["free"]), "eval_free_k": f"{now['free']['k']}/{now['free']['n']}",
        "eval_non_english": pct(now["non_english"]),
        "eval_distinct_first": now["distinct_first"],
        "eval_top5_occupations_take": sum(n for _, n in common),
        "eval_common_first": [f"{t} ({n})" for t, n in common],
        "demo_first_move_changed": f"{jc['scenarios']['first_move_changed']} of 5",
        "demo_top5_set_changed": f"{jc['scenarios']['top5_set_changed']} of 5",
        "demo_robust_pages": f"{jc['scenarios']['robust_ok']} of 5",
        "ilo_confirmed": second["confirmed"], "ilo_disagree": second["disagree"], "ilo_one_source": second["one_source"],
        "kpi2_it": f"{imp['it']['mean']:g}%", "kpi2_all": f"{imp['coverage']['mean']:g}%",
        "eval_commit": ev["versions"]["now"]["commit"], "judge_check_commit": jc["commit"],
    }


def as_markdown(n: dict) -> str:
    L = ["# Numbers the pitch quotes", "",
         "Generated by `python scripts/pitch_numbers.py --write` from `docs/eval_results.json` (commit "
         f"`{n['eval_commit']}`), `docs/judge_check.json` (commit `{n['judge_check_commit']}`) and "
         "`scripts/impact_report.py`. Evaluation numbers: synthetic data, not validated with real people. "
         "`tests/test_pitch_numbers.py` fails when the deck outline, the demo script or the Q&A sheet quotes "
         "another value.", "", "| Key | Value |", "|---|---|"]
    L += [f"| {k} | {'; '.join(v) if isinstance(v, list) else v} |" for k, v in n.items()]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    n = numbers()
    if a.write:
        (DOCS / "pitch" / "numbers.json").write_text(json.dumps(n, ensure_ascii=False, indent=1) + "\n",
                                                     encoding="utf-8", newline="\n")
        (DOCS / "pitch" / "numbers.md").write_text(as_markdown(n), encoding="utf-8", newline="\n")
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print(json.dumps(n, ensure_ascii=False, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
