"""Scenario regression report: what the three named scenarios change for each fictional person.

The scenarios are meant to change the result through the numbers they set (adoption speed ->
occupation outlook and skill weights -> match -> learning path), never by being tuned until the
ranking flips. So this report does not require any ranking to change. For every demo person it
states what did change between slow and fast adoption, by how much, and, when the top 3 stayed the
same, why: a stable ranking can be the correct answer.

    python scripts/scenario_report.py            # print the report
    python scripts/scenario_report.py --write    # also save it as docs/scenario_report.md

tests/test_scenarios.py checks the same properties on every run.
"""

import argparse
import json
from pathlib import Path

import matching
import outlook

ROOT = Path(__file__).resolve().parents[1]
TOP = 3


def listed(m: dict) -> bool:
    return not m["_parts"]["last"] and "current_occupation" not in m["flags"]


def person_report(person: dict, data: dict) -> dict:
    """One person under every named scenario: the top occupations, what moved and why."""
    profile = matching.prepare(matching.with_interest(dict(person)), data)
    fit = matching.field_fit(profile, data)
    ranked = {name: [m for m in matching.rank(profile, data, scenario=name, fit=fit) if listed(m)]
              for name in outlook.SCENARIOS}
    first, last = next(iter(outlook.SCENARIOS)), list(outlook.SCENARIOS)[-1]
    by_id = {name: {m["occ_id"]: (i + 1, m) for i, m in enumerate(rows)} for name, rows in ranked.items()}
    tops = {name: [m["occ_id"] for m in rows[:TOP]] for name, rows in ranked.items()}
    watched = list(dict.fromkeys(tops[first] + tops[last]))
    moves = []
    for occ_id in watched:
        (rank_a, a), (rank_b, b) = by_id[first][occ_id], by_id[last][occ_id]
        moves.append({"occ_id": occ_id, "title": a["title"], "rank": {first: rank_a, last: rank_b},
                      "total": {first: a["total"], last: b["total"]},
                      "total_move": round(b["total"] - a["total"], 1),
                      "outlook_move": round(b["outlook"]["outlook"] - a["outlook"]["outlook"], 1),
                      "skill_move": round((b["components"]["skill"]["score"] or 0)
                                          - (a["components"]["skill"]["score"] or 0), 1),
                      "ai_share": b["outlook"]["ai_share"], "status": {first: a["outlook"]["status"],
                                                                        last: b["outlook"]["status"]}})
    same_set = set(tops[first]) == set(tops[last])
    same_order = tops[first] == tops[last]
    gap = None
    if same_set and len(ranked[first]) > TOP:
        # how far the best occupation outside the top is from entering it, under the fastest scenario
        gap = round(ranked[last][TOP - 1]["total"] - ranked[last][TOP]["total"], 1)
    largest = max((abs(m["total_move"]) for m in moves), default=0.0)
    return {"profile_id": person["profile_id"], "name": person["name"], "kind": person.get("kind", "student"),
            "tops": {name: [by_id[name][o][1]["title"] for o in ids] for name, ids in tops.items()},
            "top_set_changed": not same_set, "top_order_changed": not same_order, "moves": moves,
            "largest_total_move": largest, "margin_to_enter_top": gap,
            "why_unchanged": None if not same_set else
            (f"The top {TOP} hold: the scenarios moved their totals by at most {largest:g} points, and the next "
             f"occupation is {gap:g} points behind under {last} adoption." if gap is not None else
             f"The top {TOP} hold under every scenario.")}


def report(data: dict | None = None) -> dict:
    data = data or matching.load_data()
    people = json.loads((ROOT / "data" / "sample_profiles.json").read_text(encoding="utf-8"))
    rows = [person_report(p, data) for p in people]
    return {"scenarios": {k: v["adoption"] for k, v in outlook.SCENARIOS.items()}, "top": TOP,
            "outlook_weight": matching.WEIGHTS["outlook"], "people": rows,
            "set_changed": sum(1 for r in rows if r["top_set_changed"]),
            "order_changed": sum(1 for r in rows if r["top_order_changed"])}


def as_markdown(rep: dict) -> str:
    names = list(rep["scenarios"])
    first, last = names[0], names[-1]
    out = ["# Scenario regression report", "",
           "Generated by `python scripts/scenario_report.py --write` from the data in this repository. "
           "Estimates under stated assumptions, not predictions.", "",
           "Scenarios (share of the gap to full AI use closed by "
           f"{outlook.HORIZON_YEAR}): " + ", ".join(f"{k} {v:.0%}" for k, v in rep["scenarios"].items())
           + f". Outlook is {rep['outlook_weight']:.0%} of a match.", "",
           f"Of {len(rep['people'])} fictional people, the top {rep['top']} contains different occupations under "
           f"{first} and {last} adoption for {rep['set_changed']}, and is in a different order for "
           f"{rep['order_changed']}. No ranking is required to change: the model is not tuned to make it.", ""]
    for p in rep["people"]:
        out += [f"## {p['name']} ({p['profile_id']}, {p['kind']})", ""]
        out += [f"- **{k}**: " + "; ".join(v) for k, v in p["tops"].items()]
        out += ["", f"| Occupation | Rank {first} → {last} | Match {first} → {last} | Outlook move | Skill-fit move |"
                    " AI share of tasks |", "|---|---|---|---|---|---|"]
        out += [f"| {m['title']} | {m['rank'][first]} → {m['rank'][last]} | {m['total'][first]:g} → {m['total'][last]:g} "
                f"| {m['outlook_move']:+g} | {m['skill_move']:+g} | {m['ai_share']:g}% |" for m in p["moves"]]
        out += ["", p["why_unchanged"] or
                "The top changed because faster adoption moves outlook away from occupations whose tasks are handed "
                "to AI more than average, and lowers the weight of skills AI takes over.", ""]
    return "\n".join(out)


def main() -> int:
    cli = argparse.ArgumentParser(description="What the scenarios change for each demo person, and why.")
    cli.add_argument("--write", action="store_true", help="save the report as docs/scenario_report.md")
    opts = cli.parse_args()
    text = as_markdown(report())
    print(text)
    if opts.write:
        (ROOT / "docs" / "scenario_report.md").write_text(text + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
