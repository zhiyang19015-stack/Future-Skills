"""The competition version against this one, item by item, with every number read from a result file or
counted from the two repositories. Nothing is typed by hand.

Three versions:
    v1          the competition entry (pekoremon/future-skills; a checkout passed as --v1-root)
    v2 before   commit 5e2a48f, the rewrite before the improvement plan (judge_check baseline)
    now         this checkout

Sources of the numbers:
    docs/eval_results.json        scripts/eval.py on 40 held-out synthetic people (all three versions)
    docs/judge_check.json         scripts/judge_check.py now
    docs/judge_check_baseline.json  the same checks at 5e2a48f (judge_check was written after v1, and
                                  v1 has another API, so it has no v1 column)
    the data files                counted here from both repositories

    python scripts/v1_vs_v2.py --v1-root ../repo --write     # docs/v1_vs_v2.md and docs/v1_vs_v2.json
    python scripts/v1_vs_v2.py --write                       # reuse the v1 counts kept in docs/v1_vs_v2.json
"""

import argparse
import csv
import json
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
sys.path.insert(0, str(ROOT / "scripts"))
import judge_check  # noqa: E402

KEEP = DOCS / "v1_vs_v2.json"


def rows(path: Path) -> list[dict]:
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def catalogue(root: Path, occupations: str) -> dict:
    occ = rows(root / "data" / occupations)
    res = rows(root / "data" / "learning_resources.csv")
    free = [r for r in res if (r.get("cost_myr") or "").strip() in ("0", "0.0", "0.00")]   # "varies" is not free
    non_en = [r for r in res if (r.get("language") or "en").lower() not in ("en", "english")]
    fields = {r.get("field_id") or r.get("subfield_code") for r in occ}
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True).stdout.strip()
    return {"commit": commit, "occupations": len(occ), "fields": len(fields), "resources": len(res),
            "resources_free": len(free), "resources_not_english": len(non_en),
            "languages": sorted({(r.get("language") or "en").lower() for r in res})}


def cell(s: dict | None) -> str:
    if not s:
        return "—"
    return "—" if s["pct"] is None else f"{s['pct']}% ({s['k']}/{s['n']})"


def build(v1_root: Path | None) -> dict:
    kept = json.loads(KEEP.read_text(encoding="utf-8")) if KEEP.exists() else {}
    v1 = catalogue(v1_root, "roles.csv") if v1_root else kept.get("catalogue", {}).get("v1")
    now = catalogue(ROOT, "occupations.csv")
    ev = json.loads((DOCS / "eval_results.json").read_text(encoding="utf-8"))
    jc_now = judge_check.headline(json.loads((DOCS / "judge_check.json").read_text(encoding="utf-8")))
    base_raw = json.loads((DOCS / "judge_check_baseline.json").read_text(encoding="utf-8"))
    jc_before = judge_check.headline(base_raw)
    return {"date": date.today().isoformat(), "catalogue": {"v1": v1, "now": now}, "eval": ev,
            "judge_check": {"before_commit": base_raw.get("commit"), "now_commit":
                            json.loads((DOCS / "judge_check.json").read_text(encoding="utf-8")).get("commit"),
                            "before": jc_before, "now": jc_now}}


EVAL_ROWS = [("first_ok", "First move agrees with the labels"), ("top5_ok", "Top 5 has a labelled-acceptable occupation"),
             ("top5_bad", "Top 5 has a labelled mistake (lower is better)"),
             ("first_changed", "First move differs, slow vs fast"), ("top5_set_changed", "Top 5 set differs, slow vs fast"),
             ("free", "Plan resources that are free"), ("non_english", "Plan resources not in English")]


def as_markdown(r: dict) -> str:
    v = r["eval"]["versions"]
    c1, cn = r["catalogue"]["v1"], r["catalogue"]["now"]
    L = ["# Competition version (v1) against now", "",
         f"Generated by `python scripts/v1_vs_v2.py --write` on {r['date']}. Every number is read from a result file "
         "or counted from the repositories by the script; none is typed by hand, and there are no adjectives. "
         "Evaluation numbers: synthetic data, not validated with real people.", "",
         "## 1. What each version covers (counted from its data files)", "",
         f"| Item | v1 `{c1['commit']}` | Now `{cn['commit']}` |", "|---|---|---|",
         f"| Occupations ranked | {c1['occupations']} | {cn['occupations']} |",
         f"| Fields (v1: IT sub-areas; now: O*NET major groups) | {c1['fields']} | {cn['fields']} |",
         f"| Learning resources in the catalogue | {c1['resources']} | {cn['resources']} |",
         f"| of which free | {c1['resources_free']} | {cn['resources_free']} |",
         f"| of which not in English | {c1['resources_not_english']} | {cn['resources_not_english']} |",
         f"| Resource languages | {', '.join(c1['languages'])} | {', '.join(cn['languages'])} |", "",
         "## 2. The same 40 held-out synthetic people through each version (scripts/eval.py)", "",
         "| Metric | " + " | ".join(f"{n} `{v[k]['commit']}`" for k, n in (("v1", "v1"), ("v2_before", "v2 before"), ("now", "Now"))
                                    if k in v) + " |",
         "|---|" + "---|" * sum(k in v for k in ("v1", "v2_before", "now"))]
    ks = [k for k in ("v1", "v2_before", "now") if k in v]
    for key, name in EVAL_ROWS:
        L.append(f"| {name} | " + " | ".join(cell(v[k]["summary"]["all"][key]) for k in ks) + " |")
    L.append("| Courses that should not be in the plan | " + " | ".join(
        f"{v[k]['summary']['all']['should_not']} of {v[k]['summary']['all']['listed']}" for k in ks) + " |")
    L.append("| People with no learning plan | " + " | ".join(str(v[k]["summary"]["all"]["no_plan"]) for k in ks) + " |")
    L += ["", "95% intervals and every person's row: [eval_results.md](eval_results.md). v1 read only education, skill "
          "levels and tools from each profile and knew 25 IT roles, so most of its gap is coverage.", "",
          "## 3. Judges' live checks (scripts/judge_check.py, the 5 demo people)", "",
          "judge_check was written after v1 and v1 has another API, so this table has no v1 column.", "",
          f"| Check | v2 before `{r['judge_check']['before_commit']}` | Now `{r['judge_check']['now_commit']}` |", "|---|---|---|"]
    for k, val in r["judge_check"]["now"].items():
        L.append(f"| {k} | {r['judge_check']['before'].get(k, '—')} | {val} |")
    L.append("")
    return "\n".join(L)


def main_cli() -> int:
    cli = argparse.ArgumentParser(description="v1 against now, from result files and the two repositories.")
    cli.add_argument("--v1-root", type=Path, help="a checkout of the competition version")
    cli.add_argument("--write", action="store_true")
    a = cli.parse_args()
    r = build(a.v1_root.resolve() if a.v1_root else None)
    text = as_markdown(r)
    if a.write:
        KEEP.write_text(json.dumps({"date": r["date"], "catalogue": r["catalogue"]}, indent=1) + "\n",
                        encoding="utf-8", newline="\n")
        (DOCS / "v1_vs_v2.md").write_text(text, encoding="utf-8", newline="\n")
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main_cli())
